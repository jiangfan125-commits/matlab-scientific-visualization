function applied = figureStyle(preset, targets, varargin)
%FIGURESTYLE  Apply a scoped, dated visual style to a MATLAB figure.
%
%   figureStyle('publication')                 % whole current figure
%   figureStyle('nature', ax)                  % one axes array
%   figureStyle('publication', [], 'WidthMM', 89, 'HeightMM', 60)
%   s = figureStyle('presentation')            % return the preset struct
%
%   Presets
%     'default'       everyday screen work; 10 pt, visible grid
%     'publication'   general print starting point; 8 pt, 0.6 pt axes
%     'nature'        dated flagship-Nature starting point; 7 pt, 0.5 pt
%     'presentation'  projected slides and posters; 14-16 pt, 2.5 pt lines
%
%   These are visual starting points, not journal-compliance profiles. Journal
%   rules change; verify the target journal's current instructions.
%
%   Name-value options
%     'FontName'   override the preset font. For Chinese text in a PDF, use
%                  'Microsoft YaHei' or 'SimSun'; Arial/Helvetica will fall
%                  back to a substitute glyph font and the export can differ
%                  from the screen.
%     'FontSize'   base font size in points
%     'Grid'       'on' | 'off' | 'keep' (default 'keep')
%     'Box'        'on' | 'off' | 'keep' (default 'keep'). Print presets turn
%                  the box off, which suits 2-D axes but strips the back
%                  planes of a 3-D view; pass 'on' for 3-D.
%     'WidthMM'    set the figure's physical width in millimetres
%     'HeightMM'   set the figure's physical height in millimetres
%     'Legend'     true (default) to also restyle legends
%
%   Why a function instead of copy-pasted `set(gca, ...)` lines: the same
%   eight properties were repeated in every plotting script, so the figures
%   drifted apart. One call keeps them identical and makes a later change a
%   one-line edit.
%
%   See also figurePalette, figureExport, figureAudit.

p = inputParser;
p.addParameter('FontName', '', @(v) ischar(v) || isstring(v));
p.addParameter('FontSize', [], @(v) isempty(v) || (isnumeric(v) && isscalar(v)));
p.addParameter('Grid', 'keep', @(v) ischar(v) || isstring(v));
p.addParameter('Box', 'keep', @(v) ischar(v) || isstring(v));
p.addParameter('WidthMM', [], @(v) isempty(v) || (isnumeric(v) && isscalar(v)));
p.addParameter('HeightMM', [], @(v) isempty(v) || (isnumeric(v) && isscalar(v)));
p.addParameter('Legend', true, @(v) islogical(v) || isnumeric(v));
p.parse(varargin{:});
o = p.Results;

S = presetTable();
key = lower(strtrim(char(preset)));
if ~isfield(S, key)
    error('figureStyle:unknownPreset', ...
        'Unknown preset "%s". Use default, publication, nature, or presentation.', ...
        key);
end
P = S.(key);

if nargin < 2
    targets = [];
end
if isempty(targets)
    figs = gcf;
    ax   = findall(figs, 'Type', 'axes');
else
    ax = targets(ishghandle(targets) & strcmp(get(targets, 'Type'), 'axes'));
    if isempty(ax)
        error('figureStyle:noAxes', 'No axes found in the supplied targets.');
    end
    % ancestor() is used per handle: get(ax,'Parent') returns a cell that can
    % nest when the handle list includes a Colorbar, and cell2mat then fails.
    figs = gobjects(0);
    for k = 1:numel(ax)
        fk = ancestor(ax(k), 'figure');
        if ~isempty(fk)
            figs(end+1) = fk; %#ok<AGROW>
        end
    end
    figs = unique(figs);
end

fs = P.fontSize;
if ~isempty(o.FontSize)
    fs = o.FontSize;
end
fn = char(o.FontName);
if isempty(fn)
    fn = P.fontName;
end

for k = 1:numel(ax)
    a = ax(k);
    set(a, ...
        'FontName',   fn, ...
        'FontSize',   fs, ...
        'LineWidth',  P.axesLineWidth, ...
        'TickDir',    'out', ...
        'TickLength', P.tickLength, ...
        'Box',        boxValue(P.box, o.Box), ...
        'Layer',      'top', ...
        'XColor',     P.axisColor, ...
        'YColor',     P.axisColor, ...
        'ZColor',     P.axisColor, ...
        'TitleFontWeight',   P.titleWeight, ...
        'TitleFontSizeMultiplier', P.titleScale, ...
        'LabelFontSizeMultiplier', P.labelScale, ...
        'GridColor',  P.gridColor, ...
        'GridAlpha',  P.gridAlpha, ...
        'MinorGridAlpha', P.gridAlpha * 0.6);

    %...A per-axes palette keeps every panel in one figure on the same cycle.
    if isprop(a, 'ColorOrder')
        set(a, 'ColorOrder', P.colorOrder);
    end

    switch lower(char(o.Grid))
        case 'on'
            grid(a, 'on'); box(a, boxValue(P.box, o.Box));
        case 'off'
            grid(a, 'off');
        case 'keep'
            % leave as the caller set it
        otherwise
            error('figureStyle:badGrid', 'Grid must be on, off, or keep.');
    end

    %...Restyle existing children so the preset applies to lines drawn before.
    kids = findall(a, 'Type', 'line');
    for q = 1:numel(kids)
        if isprop(kids(q), 'LineWidth')
            set(kids(q), 'LineWidth', P.lineWidth);
        end
    end
    pts = findall(a, 'Type', 'scatter');
    for q = 1:numel(pts)
        if isprop(pts(q), 'SizeData')
            set(pts(q), 'SizeData', P.markerSize^2);
        end
    end
end

for k = 1:numel(figs)
    set(figs(k), 'Color', 'w');
    if o.Legend
        lgs = findall(figs(k), 'Type', 'legend');
        for q = 1:numel(lgs)
            set(lgs(q), 'Box', P.legendBox, 'FontSize', P.legendFontSize, ...
                        'Color', 'none', 'TextColor', P.axisColor);
        end
    end
    if ~isempty(o.WidthMM) || ~isempty(o.HeightMM)
        resizeFigure(figs(k), o.WidthMM, o.HeightMM);
    end
end

applied = P;
applied.preset   = key;
applied.fontName = fn;
applied.fontSize = fs;
end


% -------------------------------------------------------------------------
function v = boxValue(presetBox, override)
if strcmpi(char(override), 'keep')
    v = presetBox;
else
    v = lower(char(override));
end
end


% -------------------------------------------------------------------------
function resizeFigure(fig, wMM, hMM)
% Figure and paper size in the same units, so print() scales without shear.
u0 = get(fig, 'Units');
set(fig, 'Units', 'centimeters');
pos = get(fig, 'Position');
w = pos(3); h = pos(4);
if ~isempty(wMM), w = wMM / 10; end
if ~isempty(hMM), h = hMM / 10; end
set(fig, 'Position', [pos(1) pos(2) w h]);
set(fig, 'PaperUnits', 'centimeters');
set(fig, 'PaperSize', [w h]);
set(fig, 'PaperPositionMode', 'manual');
set(fig, 'PaperPosition', [0 0 w h]);
set(fig, 'Units', u0);
end


