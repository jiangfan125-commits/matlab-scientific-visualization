sets.tol_dark = mk( ...
    ['222255'; '225555'; '225522'; '666633'; '663333'; '555555'], ...
    '6 dark colours for foreground text', ...
    'Tol SRON/EPS/TN/09-002 3.2 (2021)', ...
    'Not for multi-series lines or maps.');

sets.tol_light = mk( ...
    ['77AADD'; 'EE8866'; 'EEDD88'; 'FFAABB'; ...
     '99DDFF'; '44BB99'; 'BBCC33'; 'AAAA00'; 'DDDDDD'], ...
    '9 light colours for labelled cell fills', ...
    'Tol SRON/EPS/TN/09-002 3.2 (2021)', ...
    'Designed for fills; weak as line colours.');
end


% -------------------------------------------------------------------------
function S = mk(hexRows, note, source, caveat)
S.rgb    = hex2rgb(hexRows);
S.note   = note;
S.source = source;
S.caveat = caveat;
end


% -------------------------------------------------------------------------
function rgb = hex2rgb(h)
h = char(h);
if size(h, 2) ~= 6
    error('figurePalette:badHex', 'Hex colours must be six characters.');
end
rgb = zeros(size(h, 1), 3);
for k = 1:size(h, 1)
    rgb(k, :) = [hex2dec(h(k, 1:2)), ...
                 hex2dec(h(k, 3:4)), ...
                 hex2dec(h(k, 5:6))] / 255;
end
end