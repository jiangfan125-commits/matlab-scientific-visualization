    ['E69F00'; '56B4E9'; '009E73'; 'F0E442'; ...
     '0072B2'; 'D55E00'; 'CC79A7'; '000000'], ...
    '8 colours; light ones need outlines on white', ...
    'Wong, Nature Methods 8, 441 (2011)', ...
    'Yellow and sky blue fall below 3:1 on white.');

sets.okabe_ito_on_white = mk( ...
    ['0072B2'; 'D55E00'; '009E73'; 'CC79A7'; '000000'], ...
    '5 colours that clear 3:1 on white', ...
    'Wong (2011), subset by WCAG sRGB contrast', ...
    'Not a published palette; still add markers or line styles.');

sets.wong = mk( ...
    ['000000'; 'E69F00'; '56B4E9'; '009E73'; ...
     'F0E442'; '0072B2'; 'D55E00'; 'CC79A7'], ...
    'same eight colours, black first', ...
    'Wong (2011), alternate order', ...
    'Order differs from okabe_ito; pick one and keep it.');

sets.tol_bright = mk( ...
    ['4477AA'; 'EE6677'; '228833'; 'CCBB44'; ...
     '66CCEE'; 'AA3377'; 'BBBBBB'], ...
    '7 colours, colour-blind safe', ...
    'Tol SRON/EPS/TN/09-002 3.2 (2021)', ...
    'Weaker grayscale separation than tol_high_contrast.');

sets.tol_high_contrast = mk( ...
    ['004488'; 'DDAA33'; 'BB5566'], ...
    '3 colours; strongest grayscale separation', ...
    'Tol SRON/EPS/TN/09-002 3.2 (2021)', ...
    'Only three series fit.');

sets.tol_vibrant = mk( ...
    ['EE7733'; '0077BB'; '33BBEE'; 'EE3377'; ...
     'CC3311'; '009988'; 'BBBBBB'], ...
    '7 colours, saturated', ...
    'Tol SRON/EPS/TN/09-002 3.2 (2021)', ...
    'Bright colours can look louder than the data warrants.');

