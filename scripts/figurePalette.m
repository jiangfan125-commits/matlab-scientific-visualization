function [C, meta] = figurePalette(name, n)
%FIGUREPALETTE  Categorical palettes designed for colour-vision separability.
%
%   C = figurePalette()                    % default: okabe_ito_on_white
%   C = figurePalette('okabe_ito')         % all eight Wong colours
%   C = figurePalette('tol_bright', 4)     % first four only
%   [C, meta] = figurePalette('okabe_ito') % metadata about the scheme
%   figurePalette('list')                  % print what is available
%
%   C is n-by-3 with values in [0 1], ready for Line.Color or ax.ColorOrder.
%
%   Why not the MATLAB default order: its seven colours were chosen for
%   on-screen distinctness, not for colour-vision deficiency, and several sit
%   at similar perceived lightness. Okabe-Ito (Wong, Nature Methods 8, 441,
%   2011) and the Paul Tol schemes were designed and tested for separation.
%   A good palette still does not make a figure accessible on its own - pair
%   every colour with a marker, a line style, or a direct label.
%
%   Palettes with many light colours (tol_pale, tol_light) fail 3:1 contrast
%   against white for thin lines. Use them for filled areas and cell
%   backgrounds, not for line series. Run figureAudit to check any palette
%   against your actual background.
%
%   See also figureAudit, figureStyle, figureColormap.

if nargin < 1 || isempty(name)
    name = 'okabe_ito_on_white';
end
if nargin < 2 || isempty(n)
    n = Inf;
end

sets = paletteData();

if ischar(name) && strcmpi(strtrim(name), 'list')
    keys = fieldnames(sets);
    fprintf('\n%-22s %-4s %s\n', 'palette', 'max', 'note');
    fprintf('%s\n', repmat('-', 1, 78));
    for k = 1:numel(keys)
        S = sets.(keys{k});
        fprintf('%-22s %-4d %s\n', keys{k}, size(S.rgb, 1), S.note);
    end
    fprintf('\n');
    if nargout > 0
        C = keys;
    end
    return
end

if ~ischar(name)
    error('figurePalette:badName', 'Palette name must be a char row vector.');
end

key = lower(strtrim(name));
if ~isfield(sets, key)
    error('figurePalette:unknownPalette', ...
        ['Unknown palette "%s". Run figurePalette(''list'') to see ' ...
         'the available names.'], name);
end

S = sets.(key);
nAvail = size(S.rgb, 1);

if ~isfinite(n)
    n = nAvail;
end
if n > nAvail
    error('figurePalette:tooManySeries', ...
        ['Palette "%s" defines %d colours; %d were requested. Use fewer ' ...
         'series, use a larger scheme (tol_muted has 9), or split the ' ...
         'series across panels rather than interpolating a qualitative ' ...
         'palette - interpolation invents colours nobody tested.'], ...
        key, nAvail, n);
end

C = S.rgb(1:n, :);
meta = struct('name', key, 'note', S.note, 'maxSeries', nAvail, ...
              'source', S.source, 'caveat', S.caveat);
end


